SELECT
    customer_segment,

    COUNT(*) AS customer_count,

    SUM(frequency) AS total_orders,

    SUM(monetary_value) AS total_revenue,

    ROUND(
        AVG(monetary_value),
        2
    ) AS average_customer_value

FROM segmented_customers

GROUP BY
    customer_segment

ORDER BY
    total_revenue DESC;


