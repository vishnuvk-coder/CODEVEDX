-- QUERY 18: Final RFM Customer Report
-- ============================================================

WITH customer_metrics AS
(
    SELECT
        c.customer_id,

        MAX(o.order_date) AS last_order_date,

        DATEDIFF(
            (SELECT MAX(order_date) FROM orders),
            MAX(o.order_date)
        ) AS recency_days,

        COUNT(DISTINCT o.order_id) AS frequency,

        SUM(oi.quantity * p.price) AS monetary_value

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_items oi
        ON o.order_id = oi.order_id

    JOIN products p
        ON oi.product_id = p.product_id

    GROUP BY
        c.customer_id
)

SELECT
    customer_id,
    last_order_date,
    recency_days,
    frequency,
    monetary_value,

    CASE

        WHEN recency_days <= 30
             AND frequency >= 5
             AND monetary_value >= 10000
        THEN 'Champions'

        WHEN recency_days <= 60
             AND frequency >= 3
        THEN 'Loyal Customers'

        WHEN recency_days <= 30
             AND frequency <= 2
        THEN 'New Customers'

        WHEN recency_days > 90
             AND frequency >= 3
        THEN 'At Risk Customers'

        WHEN recency_days > 90
             AND monetary_value >= 5000
        THEN 'High Value At Risk'

        ELSE 'Regular Customers'

    END AS customer_segment

FROM customer_metrics

ORDER BY
    monetary_value DESC;


