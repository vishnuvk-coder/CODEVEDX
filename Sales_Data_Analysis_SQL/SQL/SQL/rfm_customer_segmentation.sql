-- ============================================================
-- QUERY 15: Customer Order Frequency Ranking
-- ============================================================

WITH customer_orders AS
(
    SELECT
        c.customer_id,

        COUNT(DISTINCT o.order_id) AS total_orders

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    GROUP BY
        c.customer_id
)

SELECT
    customer_id,
    total_orders,

    DENSE_RANK() OVER (
        ORDER BY total_orders DESC
    ) AS frequency_rank

FROM customer_orders

ORDER BY
    frequency_rank;


-- ============================================================
-- QUERY 16: Customer Lifetime Value
-- ============================================================

SELECT
    c.customer_id,

    COUNT(DISTINCT o.order_id) AS total_orders,

    SUM(oi.quantity * p.price) AS lifetime_value,

    ROUND(
        SUM(oi.quantity * p.price)
        /
        COUNT(DISTINCT o.order_id),
        2
    ) AS average_order_value

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    c.customer_id

ORDER BY
    lifetime_value DESC;


-- ============================================================
-- QUERY 17: Customers with High Lifetime Value
-- ============================================================

SELECT
    c.customer_id,

    SUM(oi.quantity * p.price) AS lifetime_value

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    c.customer_id

HAVING
    lifetime_value >
    (
        SELECT
            AVG(customer_revenue)

        FROM
        (
            SELECT
                SUM(oi2.quantity * p2.price)
                AS customer_revenue

            FROM orders o2

            JOIN order_items oi2
                ON o2.order_id = oi2.order_id

            JOIN products p2
                ON oi2.product_id = p2.product_id

            GROUP BY
                o2.customer_id

        ) AS revenue_table
    )

ORDER BY
    lifetime_value DESC;


