-- Recency:
-- Number of days since the customer's most recent order.
--
-- Frequency:
-- Number of unique orders placed by the customer.
--
-- Monetary:
-- Total revenue generated by the customer.


-- ============================================================
-- QUERY 5: Customer RFM Base Analysis
-- ============================================================

SELECT
    c.customer_id,

    MAX(o.order_date) AS last_order_date,

    COUNT(DISTINCT o.order_id) AS frequency,

    SUM(oi.quantity * p.price) AS monetary_value

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    c.customer_id

ORDER BY
    monetary_value DESC;


-- ============================================================
-- QUERY 6: Calculate Customer Recency
-- ============================================================

SELECT
    c.customer_id,

    MAX(o.order_date) AS last_order_date,

    DATEDIFF(
        (SELECT MAX(order_date) FROM orders),
        MAX(o.order_date)
    ) AS recency_days,

    COUNT(DISTINCT o.order_id) AS frequency,

    SUM(oi.quantity * p.price) AS monetary_value

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    c.customer_id

ORDER BY
    recency_days ASC;


-- ============================================================
-- QUERY 7: RFM Scores
-- ============================================================

WITH rfm AS
(
    SELECT
        c.customer_id,

        DATEDIFF(
            (SELECT MAX(order_date) FROM orders),
            MAX(o.order_date)
        ) AS recency_days,

        COUNT(DISTINCT o.order_id) AS frequency,

        SUM(oi.quantity * p.price) AS monetary_value

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_items oi
        ON o.order_id = oi.order_id

    JOIN products p
        ON oi.product_id = p.product_id

    GROUP BY
        c.customer_id
)

SELECT
    customer_id,
    recency_days,
    frequency,
    monetary_value,

    NTILE(5) OVER (
        ORDER BY recency_days DESC
    ) AS recency_score,

    NTILE(5) OVER (
        ORDER BY frequency
    ) AS frequency_score,

    NTILE(5) OVER (
        ORDER BY monetary_value
    ) AS monetary_score

FROM rfm

ORDER BY
    monetary_value DESC;


